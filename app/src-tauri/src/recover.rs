//! Recovery bin commands for the Recover tab.

use serde::Serialize;

use cleaner_core::recovery::{
    Batch, BatchSummary, Conflict, DriveUsage, PurgeReport, RecoveryStore, RestoreReport,
};
use cleaner_core::safety::Guard;
use cleaner_core::settings::{BinLimits, Settings};

use crate::cleaning::data_dir;

type CmdResult<T> = Result<T, String>;

const MAX_ITEM_IDS: usize = 100_000;

fn store() -> CmdResult<(RecoveryStore, BinLimits)> {
    let data = data_dir()?;
    let settings = Settings::load(&data);
    Ok((RecoveryStore::open(&data, settings.bin), settings.bin))
}

/// Batch IDs are generated by the app (`20261017T120000Z-1a2b03`); refuse
/// anything else before it reaches the store.
fn check_batch_id(id: &str) -> CmdResult<()> {
    let ok = !id.is_empty()
        && id.len() <= 64
        && id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-');
    if ok {
        Ok(())
    } else {
        Err("Unknown recovery batch.".into())
    }
}

fn check_items(items: &Option<Vec<u32>>) -> CmdResult<()> {
    match items {
        Some(ids) if ids.is_empty() => Err("Select at least one file.".into()),
        Some(ids) if ids.len() > MAX_ITEM_IDS => Err("Too many files selected.".into()),
        _ => Ok(()),
    }
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryOverview {
    batches: Vec<BatchSummary>,
    usage: Vec<DriveUsage>,
    limits: BinLimits,
}

#[tauri::command(async)]
pub fn recovery_overview() -> CmdResult<RecoveryOverview> {
    let (store, limits) = store()?;
    Ok(RecoveryOverview {
        batches: store.list().map_err(|e| e.to_string())?,
        usage: store.usage().map_err(|e| e.to_string())?,
        limits,
    })
}

#[tauri::command(async)]
pub fn recovery_batch(batch_id: String) -> CmdResult<Batch> {
    check_batch_id(&batch_id)?;
    store()?.0.batch(&batch_id).map_err(|e| e.to_string())
}

/// Original locations that are taken now, so the UI can ask what to do.
#[tauri::command(async)]
pub fn recovery_conflicts(batch_id: String, item_ids: Option<Vec<u32>>) -> CmdResult<Vec<String>> {
    check_batch_id(&batch_id)?;
    check_items(&item_ids)?;
    let batch = store()?.0.batch(&batch_id).map_err(|e| e.to_string())?;
    Ok(batch
        .items
        .iter()
        .filter(|i| item_ids.as_ref().is_none_or(|ids| ids.contains(&i.id)))
        .filter(|i| std::fs::symlink_metadata(&i.original).is_ok())
        .map(|i| i.original.display().to_string())
        .collect())
}

#[tauri::command(async)]
pub fn recovery_restore(
    batch_id: String,
    item_ids: Option<Vec<u32>>,
    conflict: Conflict,
) -> CmdResult<RestoreReport> {
    check_batch_id(&batch_id)?;
    check_items(&item_ids)?;
    let (store, _) = store()?;
    store
        .restore(&batch_id, item_ids.as_deref(), conflict, &Guard::system())
        .map_err(|e| e.to_string())
}

/// Secure delete is only used when the user turned it on in Settings.
fn check_secure(secure: bool) -> CmdResult<()> {
    if secure && !Settings::load(&data_dir()?).secure_delete {
        return Err("Secure delete is turned off in Settings.".into());
    }
    Ok(())
}

#[tauri::command(async)]
pub fn recovery_delete(batch_id: String, secure: bool) -> CmdResult<PurgeReport> {
    check_batch_id(&batch_id)?;
    check_secure(secure)?;
    store()?
        .0
        .delete_batch(&batch_id, secure)
        .map_err(|e| e.to_string())
}

#[tauri::command(async)]
pub fn recovery_empty(secure: bool) -> CmdResult<PurgeReport> {
    check_secure(secure)?;
    store()?.0.empty(secure).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn batch_ids_are_checked() {
        assert!(check_batch_id("20261017T120000Z-1a2b03").is_ok());
        for bad in ["", "../x", r"a\b", "a/b", "a b", &"x".repeat(65)] {
            assert!(check_batch_id(bad).is_err(), "{bad}");
        }
        assert!(check_items(&Some(Vec::new())).is_err());
        assert!(check_items(&None).is_ok());
    }
}
